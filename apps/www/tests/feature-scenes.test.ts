import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';
import { describe, expect, it } from 'vitest';

import manifest from '../src/data/feature-scenes.json';
import { featureSections } from '../src/data/features';
import {
  asSceneSpec,
  assertLayerFits,
  layerBottom,
  MAX_BOTTOM,
  MAX_STORY_MS,
  MAX_TILES_PER_STEP,
  scenes,
  type SceneSpec,
  STEP_SETTLE_MS,
} from '../src/data/scenes';
import chat from '../src/data/scenes/chat.json';

/**
 * The homepage feature scenes: specs in src/data/scenes/*.json, images and manifest generated by
 * scripts/build-feature-scenes.ts and committed. These checks catch a stale manifest, a missing or
 * resized image, a layer that would hang off its stage, and stories that break their own rules.
 */
const PUBLIC_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../public');

interface Files {
  dark: string;
  light: string;
}

interface LayerImages {
  files: Files;
  width: number;
  height: number;
  tiles: { files: Files; box: { left: number; top: number; width: number; height: number } }[];
  swap?: { files: Files };
}

const images = manifest as Record<string, Record<string, LayerImages>>;
const clone = (): SceneSpec => structuredClone(chat) as SceneSpec;

async function expectThemedPair(files: Files, size?: { width: number; height: number }) {
  for (const file of [files.dark, files.light]) {
    expect(file).toMatch(/^\/images\/scenes\/[\w-]+\.webp$/);
    const onDisk = path.join(PUBLIC_DIR, file);
    expect(existsSync(onDisk), file).toBe(true);
    if (size) {
      const { width, height } = await sharp(onDisk).metadata();
      expect({ width, height }, file).toEqual(size);
    }
  }
  expect(files.light).toBe(files.dark.replace(/\.webp$/, '-light.webp'));
}

describe('feature scenes', () => {
  it('give every homepage scene a feature section with a homepage pitch', () => {
    expect(scenes.length).toBeGreaterThan(0);
    for (const scene of scenes) {
      const pitch = featureSections.find((candidate) => candidate.slug === scene.slug)?.homepage;
      expect(pitch?.headline.trim(), scene.slug).toBeTruthy();
      expect(pitch?.body.trim(), scene.slug).toBeTruthy();
      expect(pitch?.caption.trim(), scene.slug).toBeTruthy();
    }
    expect(new Set(scenes.map((scene) => scene.slug)).size).toBe(scenes.length);
  });

  it('have a generated image set for every scene and layer, and nothing else', () => {
    expect(Object.keys(images).sort()).toEqual(scenes.map((scene) => scene.slug).sort());
    for (const scene of scenes) {
      expect(Object.keys(images[scene.slug] ?? {}).sort(), scene.slug).toEqual(
        scene.layers.map((layer) => layer.id).sort()
      );
    }
  });

  it.each(scenes.map((scene) => [scene.slug, scene] as const))(
    '%s: every image exists in both themes at its recorded size',
    async (_slug, scene) => {
      for (const layer of scene.layers) {
        const layerImages = images[scene.slug]?.[layer.id];
        if (!layerImages) throw new Error(`${scene.slug}.${layer.id} has no images`);
        await expectThemedPair(layerImages.files, {
          width: layerImages.width,
          height: layerImages.height,
        });
        expect(layerImages.tiles).toHaveLength(layer.tiles?.length ?? 0);
        for (const tile of layerImages.tiles) {
          await expectThemedPair(tile.files);
          const { left, top, width, height } = tile.box;
          expect(left).toBeGreaterThanOrEqual(0);
          expect(top).toBeGreaterThanOrEqual(0);
          expect(left + width).toBeLessThanOrEqual(100.001);
          expect(top + height).toBeLessThanOrEqual(100.001);
        }
        expect(Boolean(layerImages.swap)).toBe(Boolean(layer.swap));
        if (layerImages.swap) await expectThemedPair(layerImages.swap.files);
      }
    }
  );

  it.each(scenes.map((scene) => [scene.slug, scene] as const))(
    '%s: every layer fits its stage in both compositions',
    (_slug, scene) => {
      for (const layer of scene.layers) {
        const image = images[scene.slug]?.[layer.id] ?? { width: 1, height: 1 };
        for (const layout of ['wide', 'narrow'] as const) {
          const bottom = layerBottom(layer.place[layout], scene.aspect[layout], image);
          expect(bottom, `${layer.id} (${layout})`).toBeLessThanOrEqual(MAX_BOTTOM);
        }
        expect(() => assertLayerFits(scene, layer, image)).not.toThrow();
      }
    }
  );

  it.each(scenes.map((scene) => [scene.slug, scene] as const))(
    '%s: the story rests on real UI only and ends within the motion budget',
    (_slug, scene) => {
      const last = scene.beats.length;
      expect((scene.beats.at(-1) ?? 0) + STEP_SETTLE_MS).toBeLessThanOrEqual(MAX_STORY_MS);
      for (const layer of scene.layers) {
        for (const ring of layer.rings ?? []) expect(ring.until).toBeLessThanOrEqual(last);
        for (const tile of layer.tiles ?? []) expect(tile.at).toBeLessThanOrEqual(last);
      }
      // Something appears during the story: a resting frame alone is not an animation.
      const steps = scene.layers.flatMap((layer) => [
        layer.at,
        ...(layer.tiles ?? []).map((tile) => tile.at),
        ...(layer.rings ?? []).flatMap((ring) => ring.stops.map((stop) => stop.at)),
        layer.swap?.at,
      ]);
      expect(steps.filter((step) => step !== undefined).length).toBeGreaterThan(0);
    }
  );
});

describe('scene validation', () => {
  it('accepts a committed scene unchanged', () => {
    expect(asSceneSpec(clone()).slug).toBe('chat');
  });

  it('rejects a story longer than the 5 second motion budget', () => {
    const spec = clone();
    spec.beats = [...spec.beats.slice(0, -1), MAX_STORY_MS];
    expect(() => asSceneSpec(spec)).toThrow(/keep it within 5000 ms/);
  });

  it('rejects a highlight ring that would stay in the resting frame', () => {
    const spec = clone();
    const ring = spec.layers[1]?.rings?.[0];
    if (!ring) throw new Error('chat scene has no ring');
    ring.until = spec.beats.length + 1;
    expect(() => asSceneSpec(spec)).toThrow(/ring until step/);
  });

  it('rejects a highlight around something outside its crop', () => {
    const spec = clone();
    const stop = spec.layers[1]?.rings?.[0]?.stops[0];
    if (!stop) throw new Error('chat scene has no ring stop');
    stop.box = { ...stop.box, x: stop.box.x - 400 };
    expect(() => asSceneSpec(spec)).toThrow(/outlines something outside its box/);
  });

  it('rejects a chip placed where perspective would push it off the stage', () => {
    const spec = clone();
    const chip = spec.layers[1];
    if (!chip) throw new Error('chat scene has no chip');
    chip.place.narrow = { ...chip.place.narrow, x: 10, w: 89 };
    expect(() => asSceneSpec(spec)).toThrow(/reaches past 96% of the stage/);
  });

  it('rejects a main window that arrives mid-story', () => {
    const spec = clone();
    const window = spec.layers[0];
    if (!window) throw new Error('chat scene has no window');
    window.at = 2;
    expect(() => asSceneSpec(spec)).toThrow(/first layer is the main window/);
  });

  it('rejects a swap to a later state before every tile has appeared', () => {
    const spec = clone();
    const window = spec.layers[0];
    if (!window) throw new Error('chat scene has no window');
    window.swap = { source: 'sam-chat-tool-stream', at: 1 };
    expect(() => asSceneSpec(spec)).toThrow(/swaps before all its tiles appear/);
  });

  it('rejects more tiles in one step than its stagger can show within a step', () => {
    const spec = clone();
    const window = spec.layers[0];
    const tile = window?.tiles?.[1];
    if (!window || !tile) throw new Error('chat scene has no tiles');
    window.tiles = Array.from({ length: MAX_TILES_PER_STEP + 1 }, () => ({ ...tile }));
    expect(() => asSceneSpec(spec)).toThrow(/more than 5 tiles in step/);
  });

  it('rejects a layer that would hang below its stage', () => {
    const spec = clone();
    const chip = spec.layers[1];
    if (!chip) throw new Error('chat scene has no chip');
    const image = images.chat?.[chip.id] ?? { width: 1, height: 1 };
    expect(() => assertLayerFits(spec, chip, image)).not.toThrow();
    chip.place.wide = { ...chip.place.wide, y: MAX_BOTTOM - 1 };
    expect(() => assertLayerFits(spec, chip, image)).toThrow(/reaches .*% of the wide stage/);
  });
});
