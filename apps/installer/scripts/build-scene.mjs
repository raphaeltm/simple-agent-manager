// Compile the homepage's actual renderer; keep the deployed installer self-contained.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const source = new URL('../../../packages/ui/src/glass/', import.meta.url);
const output = new URL('../public/scene/', import.meta.url);
await mkdir(output, { recursive: true });
for (const name of ['node-field', 'field-model', 'palette']) {
  const input = await readFile(new URL(`${name}.ts`, source), 'utf8');
  const { outputText } = ts.transpileModule(input, {
    fileName: fileURLToPath(new URL(`${name}.ts`, source)),
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  });
  await writeFile(
    new URL(`${name}.js`, output),
    outputText.replace(/from '(\.\/[^']+)'/g, "from '$1.js'")
  );
}
// Carry the real brand into the independently owned maintenance Worker. Embedding
// these assets avoids requests back to our hosted installer after handoff.
const font = await readFile(new URL('../public/fonts/Chillax-Variable.woff2', import.meta.url));
const icon = await readFile(new URL('../public/brand-icon.png', import.meta.url));
await writeFile(
  new URL('../src/maintenance-brand.generated.ts', import.meta.url),
  '// Generated by scripts/build-scene.mjs.\n/* eslint-disable */\nexport const maintenanceBrand = ' +
    JSON.stringify({
      fontFace: `@font-face{font-family:Chillax;src:url(data:font/woff2;base64,${font.toString('base64')}) format("woff2");font-weight:200 700;font-display:swap}`,
      iconUrl: `data:image/png;base64,${icon.toString('base64')}`,
    }) +
    ';\n'
);
