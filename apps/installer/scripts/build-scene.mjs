// Compile the homepage's actual renderer; keep the deployed installer self-contained.
import { readFile, mkdir, writeFile, copyFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const app = fileURLToPath(new URL('..', import.meta.url));
const source = new URL('../../../packages/ui/src/glass/', import.meta.url);
const output = new URL('../public/scene/', import.meta.url);
await mkdir(output, { recursive: true });
for (const name of ['node-field', 'field-model', 'palette']) {
  const input = await readFile(new URL(`${name}.ts`, source), 'utf8');
  const { outputText } = ts.transpileModule(input, {
    fileName: fileURLToPath(new URL(`${name}.ts`, source)),
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  });
  await writeFile(
    new URL(`${name}.js`, output),
    outputText.replace(/from '(\.\/[^']+)'/g, "from '$1.js'")
  );
}
// Assets are build inputs, never hand-maintained copies.
await mkdir(new URL('../public/fonts/', import.meta.url), { recursive: true });
for (const [source, target] of [
  [
    '../../../apps/www/public/fonts/Chillax-Variable.woff2',
    '../public/fonts/Chillax-Variable.woff2',
  ],
  ['../../../apps/www/public/fonts/Chillax-Variable.woff', '../public/fonts/Chillax-Variable.woff'],
  ['../../../apps/www/public/favicon.png', '../public/brand-icon.png'],
  ['../../../apps/www/public/images/sam-head.png', '../public/sam-head.png'],
])
  await copyFile(new URL(source, import.meta.url), new URL(target, import.meta.url));
await copyFile(
  new URL('../../../packages/ui/src/brand/theme-init.js', import.meta.url),
  new URL('../public/theme-init.js', import.meta.url)
);
execFileSync('pnpm', ['exec', 'astro', 'build'], { cwd: app, stdio: 'inherit' });
const font = await readFile(new URL('../public/fonts/Chillax-Variable.woff2', import.meta.url));
const icon = await readFile(new URL('../public/brand-icon.png', import.meta.url));
const iconUrl = `data:image/png;base64,${icon.toString('base64')}`;
let shell = await readFile(
  new URL('../site-static/maintenance-shell.html', import.meta.url),
  'utf8'
);
const [hostedBefore, hostedAfter] = shell
  .replaceAll('BRAND_ICON', '/brand-icon.png')
  .split('SAM_MAINTENANCE_CONTENT');
for (const match of [...shell.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g)]) {
  const css = await readFile(new URL('../site-static' + match[1], import.meta.url), 'utf8');
  shell = shell.replace(match[0], `<style>${css}</style>`);
}
// Inline the local compiled scripts so maintenance has no origin dependencies.
for (const match of [...shell.matchAll(/<script\b([^>]*?)src="([^"]+)"([^>]*)><\/script>/g)]) {
  const code = await readFile(new URL('../site-static' + match[2], import.meta.url), 'utf8');
  shell = shell.replace(match[0], `<script type="module">${code}</script>`);
}
shell = shell
  .replaceAll('BRAND_ICON', iconUrl)
  .replace(
    /<style>/,
    `<style>@font-face{font-family:Chillax;src:url(data:font/woff2;base64,${font.toString('base64')}) format("woff2");font-weight:200 700;font-display:swap}`
  );
shell = shell.replace(
  /url\(([^)]*Chillax-Variable\.woff2?[^)]*)\)/g,
  `url(data:font/woff2;base64,${font.toString('base64')})`
);
const scriptHashes = [...shell.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)]
  .map((m) => "'sha256-" + createHash('sha256').update(m[1]).digest('base64') + "'")
  .join(' ');
const [before, after] = shell.split('SAM_MAINTENANCE_CONTENT');
if (!before || !after) throw new Error('Maintenance shell content marker missing');
await writeFile(
  new URL('../src/maintenance-brand.generated.ts', import.meta.url),
  '// Generated by scripts/build-scene.mjs.\n/* eslint-disable */\nexport const maintenanceBrand = ' +
    JSON.stringify({ before, after, scriptHashes }) +
    ';\nexport const installerShell = ' +
    JSON.stringify({ before: hostedBefore, after: hostedAfter }) +
    ';\n'
);
await rm(new URL('../site-static/maintenance-shell.html', import.meta.url));
