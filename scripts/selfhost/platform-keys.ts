/**
 * Platform keys for a celld box, generated once and then reused.
 *
 * On Cloudflare, the same groups are created once into the API Worker
 * (`scripts/deploy/installation-keys.ts`). A self-hosted box generates the same shapes with
 * the local-dev generators in `scripts/deploy/generate-keys.ts` and keeps them in a
 * root-only file (`<state-dir>/platform-keys.json`). They are never regenerated: a new
 * ENCRYPTION_KEY would make every stored credential undecryptable, and a new SAM_INSTALLATION_ID
 * would orphan the box's VMs.
 *
 * When the file does not exist, keys are created only by `pnpm selfhost:deploy --init` on a
 * state dir with no trace of an earlier deploy (`PRIOR_DEPLOY_EVIDENCE`). Both conditions are
 * required: a plain deploy or an upgrade pointed at the wrong state dir must stop rather than
 * mint a second identity for the install.
 *
 * When the file exists, only `--init` completes a key group it lacks (`pnpm selfhost:upgrade`
 * runs `deploy --init` first), and never an identity group (`ENCRYPTION_KEY`,
 * `SAM_INSTALLATION_ID`): every platform-keys.json ever written has had both, so one missing from
 * the file was lost, not added by a newer version, and regenerating it would replace the key the
 * box already uses.
 */

import { randomBytes } from 'node:crypto';
import { existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

import { LOCAL_BUNDLE_SUBDIR } from '../../deploy/selfhost/key-agent/bundle-store.ts';
import { generateDeploySigningKeyPair } from '../deploy/deploy-signing-keys.js';
import {
  generateEncryptionKey,
  generateKeyPair,
  generateVapidKeyPair,
} from '../deploy/generate-keys.js';
import { CONFIG_FILE } from './celld-project.js';
import { MAIL_COLLECTOR_ENV_FILE } from './mail-settings.js';
import { readPrivateJson, replacePrivateFile } from './secret-files.js';

export const PLATFORM_KEYS_FILE = 'platform-keys.json';

/**
 * Paths, relative to the state dir, that only exist once a box has had platform keys. Seeing any
 * of them without platform-keys.json means the file was lost or moved, not never created, and
 * generating new keys would make every stored credential unreadable and orphan the box's nodes.
 * A directory counts only when it is not empty.
 */
export const PRIOR_DEPLOY_EVIDENCE: readonly string[] = [
  // The secrets-free Worker config every deploy leaves behind (celld-project.ts writeCelldConfig).
  join('project', CONFIG_FILE),
  // Rendered from REVERSE_TUNNEL_GATEWAY_SECRET by --init and every deploy (deploy-steps.ts).
  'gateway.env',
  // Caddy's collector settings, written by --init and every deploy (mail-settings.ts).
  MAIL_COLLECTOR_ENV_FILE,
  // Sealed key bundles: a box that keeps its keys sealed instead of in platform-keys.json, which
  // this deploy cannot open.
  LOCAL_BUNDLE_SUBDIR,
];

/** What the deploy is doing: whether it may create or write keys. */
export type PlatformKeysMode = 'init' | 'deploy' | 'dry-run';

/** Stands in for a key a dry run would generate; never written anywhere. */
export const DRY_RUN_KEY_PLACEHOLDER = '<generated by --init>';

/** Every key the box needs; a keys file missing any of them is completed, never replaced. */
export const PLATFORM_KEY_NAMES = [
  'ENCRYPTION_KEY',
  'JWT_PRIVATE_KEY',
  'JWT_PUBLIC_KEY',
  'DEPLOY_SIGNING_PRIVATE_KEY',
  'DEPLOY_SIGNING_PUBLIC_KEY',
  'VAPID_PRIVATE_KEY',
  'VAPID_PUBLIC_KEY',
  'PREVIEW_SIGNING_KEY',
  'SAM_INSTALLATION_ID',
  'REVERSE_TUNNEL_GATEWAY_SECRET',
  'SAM_DNS_TSIG_SECRET',
] as const;

type PlatformKeyName = (typeof PLATFORM_KEY_NAMES)[number];

/** Generators grouped so a pair is always created together. */
const GENERATORS: ReadonlyArray<{
  names: readonly PlatformKeyName[];
  generate: () => Partial<Record<PlatformKeyName, string>>;
  /**
   * In every keys file since the first version, so its absence from an existing file means the
   * value was lost: it is restored from a backup, never regenerated. A group added later must
   * not set this, so `--init` can complete it on boxes created before it existed.
   */
  identity?: true;
  /**
   * Needed only by an optional feature (the `dns` profile): a plain deploy of a box whose keys
   * predate it skips the group instead of asking for --init, so the box deploys unchanged.
   * --init generates it; the feature refuses to start without it (dns-settings.ts).
   */
  optional?: true;
}> = [
  {
    names: ['ENCRYPTION_KEY'],
    identity: true,
    generate: () => ({ ENCRYPTION_KEY: generateEncryptionKey() }),
  },
  {
    names: ['JWT_PRIVATE_KEY', 'JWT_PUBLIC_KEY'],
    generate: () => {
      const pair = generateKeyPair();
      return { JWT_PRIVATE_KEY: pair.privateKey, JWT_PUBLIC_KEY: pair.publicKey };
    },
  },
  {
    names: ['DEPLOY_SIGNING_PRIVATE_KEY', 'DEPLOY_SIGNING_PUBLIC_KEY'],
    generate: () => {
      const pair = generateDeploySigningKeyPair();
      return {
        DEPLOY_SIGNING_PRIVATE_KEY: pair.privateKey,
        DEPLOY_SIGNING_PUBLIC_KEY: pair.publicKey,
      };
    },
  },
  {
    names: ['VAPID_PRIVATE_KEY', 'VAPID_PUBLIC_KEY'],
    generate: () => {
      const pair = generateVapidKeyPair();
      return { VAPID_PRIVATE_KEY: pair.privateKey, VAPID_PUBLIC_KEY: pair.publicKey };
    },
  },
  // Same shape as Pulumi's `preview-signing-key` (32 bytes, base64) and
  // `installation-id` (16 bytes, lowercase hex).
  {
    names: ['PREVIEW_SIGNING_KEY'],
    generate: () => ({ PREVIEW_SIGNING_KEY: randomBytes(32).toString('base64') }),
  },
  {
    names: ['SAM_INSTALLATION_ID'],
    identity: true,
    generate: () => ({ SAM_INSTALLATION_ID: randomBytes(16).toString('hex') }),
  },
  // Shared with frps and Caddy through gateway.env (box-settings.ts). The Worker authenticates
  // frps's server plugin and Caddy's forward_auth with it. Hex so it is safe in frps's plugin
  // URL userinfo. Consumed by the reverse-tunnel transport (task 01M72X0F03A7NVVJP28W9SC03Z).
  {
    names: ['REVERSE_TUNNEL_GATEWAY_SECRET'],
    generate: () => ({ REVERSE_TUNNEL_GATEWAY_SECRET: randomBytes(32).toString('hex') }),
  },
  // The TSIG key Caddy signs its RFC 2136 updates to sam-dns with (DNS on the box,
  // dns-settings.ts), rendered to dns.env for those two only. HMAC-SHA256, so 32 bytes (RFC 8945
  // section 6). Not an identity: --init adds it to boxes created before it existed.
  {
    names: ['SAM_DNS_TSIG_SECRET'],
    optional: true,
    generate: () => ({ SAM_DNS_TSIG_SECRET: randomBytes(32).toString('base64') }),
  },
];

export interface PlatformKeysResult {
  keys: Record<PlatformKeyName, string>;
  /**
   * Names generated on this run (written to the file), or for a dry run the names that would be
   * (filled with `DRY_RUN_KEY_PLACEHOLDER`, nothing written). Empty when every key existed.
   */
  generated: PlatformKeyName[];
}

function isEvidence(path: string): boolean {
  if (!existsSync(path)) return false;
  return !statSync(path).isDirectory() || readdirSync(path).length > 0;
}

/** Throws when the state dir shows an earlier deploy (`PRIOR_DEPLOY_EVIDENCE`). */
function assertNoPriorDeploy(stateDir: string, keysPath: string): void {
  const found = PRIOR_DEPLOY_EVIDENCE.map((entry) => join(stateDir, entry)).filter(isEvidence);
  if (found.length === 0) return;
  throw new Error(
    `${keysPath} does not exist, but ${found.join(', ')} show this box was deployed before. ` +
      'Generating new platform keys would make every stored credential unreadable and orphan ' +
      `the box's nodes: restore ${PLATFORM_KEYS_FILE} from your backup into ${stateDir} ` +
      '(mode 0600), or check that --state-dir / --env-file point at this box.'
  );
}

/**
 * Reads the keys file (or `{}` when there is none and `mode` may create one) and the platform
 * keys in it. A key present with an empty value is an error.
 */
function readExistingKeys(
  stateDir: string,
  path: string,
  mode: PlatformKeysMode
): { existing: Record<string, string>; keys: Record<string, string>; fileExists: boolean } {
  if (!existsSync(path)) {
    assertNoPriorDeploy(stateDir, path);
    if (mode === 'deploy') {
      throw new Error(
        `${path} does not exist; run pnpm selfhost:deploy --init first (it generates the ` +
          'platform keys once), or restore the file from your backup'
      );
    }
    return { existing: {}, keys: {}, fileExists: false };
  }
  const existing = readPrivateJson(path);
  const keys: Record<string, string> = {};
  for (const name of PLATFORM_KEY_NAMES) {
    if (!(name in existing)) continue;
    const value = existing[name] ?? '';
    if (value.trim() === '') {
      throw new Error(
        `${path}: ${name} is empty; restore its value from a backup instead of regenerating it`
      );
    }
    keys[name] = value;
  }
  return { existing, keys, fileExists: true };
}

/** Throws unless a group missing from an existing keys file may be generated in `mode`. */
function assertMayCompleteGroup(
  group: (typeof GENERATORS)[number],
  path: string,
  mode: PlatformKeysMode
): void {
  const names = group.names.join(', ');
  if (group.identity) {
    throw new Error(
      `${path} has no ${names}. Every platform-keys.json has had it, so it was lost; a new value ` +
        "would make every stored credential unreadable or orphan the box's nodes. Restore it " +
        `from your backup (${PLATFORM_KEYS_FILE}.bak or your own copy).`
    );
  }
  if (mode === 'deploy') {
    throw new Error(
      `${path} has no ${names}; run pnpm selfhost:deploy --init to generate it (a key added by a ` +
        'newer version), or restore it from your backup'
    );
  }
}

/**
 * Fills every wholly missing key group into `keys` (placeholders in a dry run) and returns the
 * names it filled. A group with only some of its keys present is an error, and so is a group
 * missing from an existing file that `assertMayCompleteGroup` does not allow.
 */
function completeKeyGroups(
  keys: Record<string, string>,
  path: string,
  mode: PlatformKeysMode,
  fileExists: boolean
): PlatformKeyName[] {
  const generated: PlatformKeyName[] = [];
  for (const group of GENERATORS) {
    const present = group.names.filter((name) => keys[name]);
    if (present.length === group.names.length) continue;
    if (present.length > 0) {
      throw new Error(
        `${path} has ${present.join(', ')} but not ${group.names.filter((n) => !keys[n]).join(', ')}; ` +
          'restore the missing value from a backup instead of regenerating the pair'
      );
    }
    if (fileExists && group.optional && mode === 'deploy') continue;
    if (fileExists) assertMayCompleteGroup(group, path, mode);
    if (mode === 'dry-run') {
      for (const name of group.names) keys[name] = DRY_RUN_KEY_PLACEHOLDER;
    } else {
      Object.assign(keys, group.generate());
    }
    generated.push(...group.names);
  }
  return generated;
}

/**
 * Loads `<stateDir>/platform-keys.json`, generating any missing group, and writes it back
 * (atomically, keeping the previous file as `.bak`) only when something was generated.
 *
 * - No file: only `init` on a state dir with no `PRIOR_DEPLOY_EVIDENCE` creates one; `deploy`
 *   refuses, and `dry-run` reports placeholders.
 * - A file missing a whole group (a key added by a newer version) is completed only in `init`
 *   (`dry-run` reports it); `deploy` refuses. A missing identity group, a pair with one half
 *   missing, or a key present with an empty value is an error in every mode: regenerating would
 *   silently rotate a key the box already uses.
 */
export function ensurePlatformKeys(stateDir: string, mode: PlatformKeysMode): PlatformKeysResult {
  const path = join(stateDir, PLATFORM_KEYS_FILE);
  const { existing, keys, fileExists } = readExistingKeys(stateDir, path, mode);
  const generated = completeKeyGroups(keys, path, mode, fileExists);
  // Any other value already in the file is kept, as before.
  const all = { ...existing, ...keys } as Record<PlatformKeyName, string>;
  if (generated.length > 0 && mode !== 'dry-run') {
    replacePrivateFile(path, `${JSON.stringify(all, null, 2)}\n`, { backup: true });
  }
  return { keys: all, generated };
}

/**
 * The platform keys of a sealed box (key-service.ts), where they live in the newest sealed
 * bundle instead of platform-keys.json: `existing` is that bundle laid under a
 * platform-keys.json still being migrated. Same rules as `ensurePlatformKeys`, writing nothing:
 * with no keys at all only `init` on a state dir with no earlier deploy generates them, a group
 * added by a newer version is completed only by `init`, and a lost identity key is never
 * regenerated. `source` names where the keys came from in errors.
 */
export function completeSealedPlatformKeys(
  stateDir: string,
  existing: Readonly<Record<string, string>>,
  source: string,
  mode: PlatformKeysMode
): PlatformKeysResult {
  const keys: Record<string, string> = {};
  for (const name of PLATFORM_KEY_NAMES) {
    if (!(name in existing)) continue;
    const value = existing[name] ?? '';
    if (value.trim() === '') {
      throw new Error(
        `${source}: ${name} is empty; restore its value from a backup instead of regenerating it`
      );
    }
    keys[name] = value;
  }
  const hasKeys = Object.keys(keys).length > 0;
  if (!hasKeys) {
    // Sealed and unsealed boxes leave the same traces (gateway.env, the project config); with
    // neither a bundle nor platform-keys.json those mean the keys were lost, not never made.
    assertNoPriorDeploy(stateDir, source);
    if (mode === 'deploy') {
      throw new Error(
        `${source} holds no platform keys; run pnpm selfhost:deploy --init first (it generates ` +
          'them once), or restore the sealed bundles or platform-keys.json from your backup'
      );
    }
  }
  const generated = completeKeyGroups(keys, source, mode, hasKeys);
  return { keys: keys as Record<PlatformKeyName, string>, generated };
}

/**
 * Generated values secrets.env may not override (deploy.ts renders secrets.env over the keys):
 * every platform key, the gateway secret frps and Caddy share and the installation id included.
 * Repeating the generated value is accepted, so a secrets.env copied from the keys still deploys.
 */
export function assertSecretsKeepPlatformKeys(
  secrets: Readonly<Record<string, string>>,
  keys: Readonly<Record<PlatformKeyName, string>>,
  secretsPath: string
): void {
  for (const name of PLATFORM_KEY_NAMES) {
    if (name in secrets && secrets[name] !== keys[name]) {
      throw new Error(
        `${secretsPath}: ${name} differs from the generated value in ${PLATFORM_KEYS_FILE}; ` +
          'remove it (the deploy sets it)'
      );
    }
  }
}
