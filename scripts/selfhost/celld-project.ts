/**
 * Materialise a celld project directory for `apps/api`.
 *
 * celld requires `main`, `assets.directory` and every D1 `migrations_dir` to sit inside the
 * project directory with no `..`, and reads migrations from flat directories only. The
 * repository keeps the observability migrations nested inside the main ones, so the project
 * gets one flat directory of symlinks per database. The real migration files are never moved.
 */

import {
  cpSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readlinkSync,
  renameSync,
  rmSync,
  symlinkSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import type { CelldConfigPlan, CelldWranglerConfig } from './celld-config.js';
import { appendSelfhostObservabilityMigrations } from './observability-migrations.js';
import { appendReverseTunnelMigrations } from './reverse-tunnel-migrations.js';
import { writePrivateFile } from './secret-files.js';
import { SELFHOST_DURABLE_OBJECTS, SELFHOST_ENTRY_MODULE } from './selfhost-durable-objects.js';

export const CONFIG_FILE = 'wrangler.json';
export const SOURCE_LINK = 'src';
export const ASSETS_DIR = 'web';
/** The generated celld entry module (renderCelldMain), sealed or not. */
export const CELLD_MAIN = 'celld-main.ts';
/** apps/api/wrangler.toml `migrations_dir` of the primary DATABASE. */
const PRIMARY_MIGRATIONS_DIR = 'src/db/migrations';
/** apps/api/wrangler.toml `migrations_dir` of OBSERVABILITY_DATABASE. */
const OBSERVABILITY_MIGRATIONS_DIR = 'src/db/migrations/observability';

const CLASS_NAME = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const SELFHOST_CLASS_NAMES = new Set(SELFHOST_DURABLE_OBJECTS.map((object) => object.className));

/** Locale-independent order, so the generated entry is identical on every machine. */
function byCodeUnit(a: string, b: string): number {
  if (a < b) return -1;
  return a > b ? 1 : 0;
}

/**
 * The celld entry: the API's own entry (`src/index.ts`, every export kept by `export *`), plus
 * what only a celld build turns on before any request runs:
 *
 * - `resumeSharedFlightJoinsOnOwnTimer()`: on celld the code that runs when a promise settles
 *   belongs to the request that settled it, so a request joining another's in-flight read must
 *   resume on its own timer (packages/worker-core/src/shared-flight.ts, imported through its
 *   apps/api/src/lib/shared-flight.ts re-export);
 * - `withSelfHostBuild` (apps/api/src/selfhost/build.ts): the speech backend, the D1 analytics
 *   sink and the reverse-tunnel transport, gateway and lease sweep.
 *
 * With `sealedClassNames` (a box whose secrets come from the key agent, key-service.ts) the
 * default handlers and every Durable Object class named are also wrapped so each runs with the
 * runtime secrets or not at all (apps/api/src/selfhost/runtime-secrets.ts); the named exports
 * shadow the ones `export *` brings in. The list comes from the deployed config, so a class added
 * to wrangler.toml or to SELFHOST_DURABLE_OBJECTS cannot be missed.
 *
 * The Cloudflare entry never imports any of these modules from here, and never sees this file
 * (apps/api/tests/unit/selfhost/selfhost-only-modules.test.ts).
 */
export function renderCelldMain(sealedClassNames?: readonly string[]): string {
  const runtime = [
    `import { resumeSharedFlightJoinsOnOwnTimer } from './${SOURCE_LINK}/lib/shared-flight.ts';`,
  ];
  if (!sealedClassNames) {
    return [
      '// Generated by scripts/selfhost/celld-project.ts (renderCelldMain). Do not edit.',
      `import worker, { app } from './${SOURCE_LINK}/index.ts';`,
      ...runtime,
      `import { withSelfHostBuild } from './${SOURCE_LINK}/${SELFHOST_ENTRY_MODULE}';`,
      '',
      'resumeSharedFlightJoinsOnOwnTimer();',
      `export * from './${SOURCE_LINK}/index.ts';`,
      ...SELFHOST_DURABLE_OBJECTS.map(
        ({ className }) =>
          `export { ${className} } from './${SOURCE_LINK}/${SELFHOST_ENTRY_MODULE}';`
      ),
      'export default withSelfHostBuild(worker, app);',
      '',
    ].join('\n');
  }
  const names = [...new Set([...sealedClassNames, ...SELFHOST_CLASS_NAMES])].sort(byCodeUnit);
  for (const name of names) {
    if (!CLASS_NAME.test(name)) throw new Error(`${name} is not a valid Durable Object class name`);
  }
  return [
    '// Generated by scripts/selfhost/celld-project.ts (renderCelldMain, sealed). Do not edit.',
    `import worker, * as api from './${SOURCE_LINK}/index.ts';`,
    ...runtime,
    `import * as selfhost from './${SOURCE_LINK}/${SELFHOST_ENTRY_MODULE}';`,
    `import { wrapDurableObject, wrapWorker } from './${SOURCE_LINK}/selfhost/runtime-secrets-socket.ts';`,
    '',
    'resumeSharedFlightJoinsOnOwnTimer();',
    `export * from './${SOURCE_LINK}/index.ts';`,
    'export default wrapWorker(selfhost.withSelfHostBuild(worker, api.app));',
    ...names.map((name) => {
      const source = SELFHOST_CLASS_NAMES.has(name) ? 'selfhost' : 'api';
      return `export const ${name} = wrapDurableObject(${source}.${name});`;
    }),
    '',
  ].join('\n');
}

export interface PrepareProjectOptions {
  /** Absolute path to apps/api. */
  apiDir: string;
  /** Absolute path to the generated project directory. */
  projectDir: string;
  plan: CelldConfigPlan;
  /** Absolute path to the apps/web build output; copied into the project when set. */
  webDist?: string;
  /** Wrap the entry with the runtime-secrets loader (a sealed box, key-service.ts). */
  runtimeSecrets?: boolean;
}

/** Points `link` at `target`, replacing a stale symlink but never a real file or directory. */
function ensureSymlink(target: string, link: string): void {
  if (existsSync(link) || isSymlink(link)) {
    if (!isSymlink(link))
      throw new Error(`${link} exists and is not a symlink; refusing to replace it`);
    if (readlinkSync(link) === target) return;
    rmSync(link);
  }
  symlinkSync(target, link);
}

function isSymlink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

/** The .sql files directly inside `dir`, sorted; subdirectories are ignored. */
export function listMigrationFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.sql'))
    .map((entry) => entry.name)
    .sort();
}

export function prepareCelldProject(options: PrepareProjectOptions): void {
  const { apiDir, projectDir, plan } = options;
  mkdirSync(projectDir, { recursive: true, mode: 0o700 });
  ensureSymlink(resolve(apiDir, 'src'), join(projectDir, SOURCE_LINK));

  for (const dir of plan.migrationDirs) {
    const source = resolve(apiDir, dir.sourceDir);
    const files = listMigrationFiles(source);
    if (files.length === 0) throw new Error(`no .sql migrations in ${source}`);
    const target = join(projectDir, dir.projectRelativeDir);
    // Rebuilt every run so a deleted or renamed migration cannot linger as a stale link.
    rmSync(target, { recursive: true, force: true });
    mkdirSync(target, { recursive: true });
    for (const file of files) symlinkSync(join(source, file), join(target, file));
    // The primary database also gets the self-host-only migrations (reverse-tunnel leases,
    // apps/api/src/selfhost/migrations/), which apps/api/wrangler.toml never lists.
    if (dir.sourceDir === PRIMARY_MIGRATIONS_DIR) appendReverseTunnelMigrations(apiDir, target);
    // OBSERVABILITY_DATABASE gets the D1 analytics sink's table the same way
    // (apps/api/src/selfhost/observability-migrations.ts).
    if (dir.sourceDir === OBSERVABILITY_MIGRATIONS_DIR) {
      appendSelfhostObservabilityMigrations(apiDir, target);
    }
  }

  const sealedClasses = options.runtimeSecrets
    ? plan.config.durable_objects.bindings.map((binding) => binding.class_name)
    : undefined;
  writePrivateFile(join(projectDir, CELLD_MAIN), renderCelldMain(sealedClasses));

  if (options.webDist) {
    if (!existsSync(join(options.webDist, 'index.html'))) {
      throw new Error(`${options.webDist} has no index.html; build apps/web first`);
    }
    const target = join(projectDir, ASSETS_DIR);
    const staging = `${target}.next`;
    rmSync(staging, { recursive: true, force: true });
    // Source maps stay out of the box: they triple the upload and the browser never needs them.
    // A symlink in the build could publish any file on the box at app.*; refuse it.
    cpSync(options.webDist, staging, {
      recursive: true,
      filter: (src) => {
        if (lstatSync(src).isSymbolicLink()) {
          throw new Error(`${src} is a symlink; the web build must contain only regular files`);
        }
        return !src.endsWith('.map');
      },
    });
    rmSync(target, { recursive: true, force: true });
    renameSync(staging, target);
  }
}

/** Writes the config with mode 0600; atomic so celld never reads a half-written file. */
export function writeCelldConfig(projectDir: string, config: CelldWranglerConfig): string {
  const path = join(projectDir, CONFIG_FILE);
  const temp = join(dirname(path), `.${CONFIG_FILE}.tmp`);
  writePrivateFile(temp, `${JSON.stringify(config, null, 2)}\n`);
  renameSync(temp, path);
  return path;
}
