import { existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { resolveTunnelPortRange } from './box-settings.js';
import {
  ensureMailCollectorPassword,
  mailCollectorEnabled,
  mailEgressEndpoints,
  renderMailCollectorEnv,
  smtpWorkerVars,
  writeMailCollectorFiles,
} from './mail-settings.js';

const DOMAIN = 'sam.example.com';
const COLLECTOR = { COMPOSE_PROFILES: 'tunnel, mail-collector' };
const RELAY = {
  SMTP_HOST: 'smtp.example.com',
  SMTP_USERNAME: 'relay-user',
  SMTP_FROM: `sign-in@${DOMAIN}`,
};

describe('smtpWorkerVars', () => {
  it('gives the Worker no SMTP settings when the box sends no email (unchanged default)', () => {
    expect(smtpWorkerVars({ COMPOSE_PROFILES: 'tunnel' }, {}, DOMAIN)).toEqual({});
  });

  it('points the Worker at the loopback collector when the profile is on', () => {
    expect(smtpWorkerVars(COLLECTOR, {}, DOMAIN)).toEqual({
      SMTP_HOST: '127.0.0.1',
      SMTP_PORT: '1025',
      SMTP_TLS: 'none',
      SMTP_FROM: `sign-in@${DOMAIN}`,
    });
    expect(
      smtpWorkerVars(
        { ...COLLECTOR, MAIL_COLLECTOR_SMTP_PORT: '2525', SMTP_FROM: 'a@b.example' },
        {},
        DOMAIN
      )
    ).toMatchObject({ SMTP_PORT: '2525', SMTP_FROM: 'a@b.example' });
  });

  it('passes a relay through and validates it with the Worker parser, password from secrets.env', () => {
    expect(smtpWorkerVars(RELAY, { SMTP_PASSWORD: 'relay-pass' }, DOMAIN)).toEqual(RELAY);
    expect(() => smtpWorkerVars(RELAY, {}, DOMAIN)).toThrow(
      'SMTP settings: SMTP_USERNAME and SMTP_PASSWORD must be set together'
    );
    expect(() =>
      smtpWorkerVars(
        { ...RELAY, SMTP_TLS: 'none', SMTP_PORT: '25' },
        { SMTP_PASSWORD: 'x' },
        DOMAIN
      )
    ).toThrow('SMTP_TLS=none is allowed only for a loopback SMTP_HOST');
  });

  it('refuses a relay and the collector together, and a password in the compose .env', () => {
    expect(() =>
      smtpWorkerVars({ ...COLLECTOR, ...RELAY }, { SMTP_PASSWORD: 'p' }, DOMAIN)
    ).toThrow('choose one place for sign-in codes');
    expect(() => smtpWorkerVars({ ...RELAY, SMTP_PASSWORD: 'p' }, {}, DOMAIN)).toThrow(
      'SMTP_PASSWORD is a secret'
    );
  });
});

describe('mail collector profile', () => {
  it('is on only when COMPOSE_PROFILES names it exactly', () => {
    expect(mailCollectorEnabled(COLLECTOR)).toBe(true);
    expect(mailCollectorEnabled({ COMPOSE_PROFILES: 'tunnel,mail-collector-x' })).toBe(false);
    expect(mailCollectorEnabled({})).toBe(false);
  });

  it('asks the egress fence for the collector SMTP port only when it runs', () => {
    expect(mailEgressEndpoints(COLLECTOR)).toEqual([{ address: '127.0.0.1', port: 1025 }]);
    expect(mailEgressEndpoints({ ...COLLECTOR, MAIL_COLLECTOR_SMTP_PORT: '2525' })).toEqual([
      { address: '127.0.0.1', port: 2525 },
    ]);
    expect(mailEgressEndpoints({ COMPOSE_PROFILES: 'tunnel' })).toEqual([]);
  });

  it('keeps node lease ranges off the collector ports even with the collector off', () => {
    expect(() =>
      resolveTunnelPortRange({
        REVERSE_TUNNEL_PORT_RANGE_START: '8020',
        REVERSE_TUNNEL_PORT_RANGE_END: '8030',
      })
    ).toThrow('MAIL_COLLECTOR_UI_PORT (8025)');
    expect(() =>
      resolveTunnelPortRange({
        REVERSE_TUNNEL_PORT_RANGE_START: '1024',
        REVERSE_TUNNEL_PORT_RANGE_END: '1100',
      })
    ).toThrow('MAIL_COLLECTOR_SMTP_PORT (1025)');
  });
});

describe('collector UI password', () => {
  let dir: string;
  let path: string;
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'sam-mail-'));
    path = join(dir, 'mail-collector-ui-password');
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  it('is generated by --init only, kept afterwards, and private', () => {
    expect(() => ensureMailCollectorPassword(path, COLLECTOR, false)).toThrow(
      'run pnpm selfhost:deploy --init first'
    );
    const generated = ensureMailCollectorPassword(path, COLLECTOR, true);
    expect(generated).toMatch(/^[0-9a-f]{64}$/);
    expect(statSync(path).mode & 0o777).toBe(0o600);
    expect(ensureMailCollectorPassword(path, COLLECTOR, false)).toBe(generated);
    expect(ensureMailCollectorPassword(path, COLLECTOR, true)).toBe(generated);
  });

  it('is not created while the profile is off', () => {
    expect(ensureMailCollectorPassword(path, {}, true)).toBeNull();
    expect(() => readFileSync(path)).toThrow();
  });

  it('refuses a password file it did not generate', () => {
    writeFileSync(path, 'hunter2\n', { mode: 0o600 });
    expect(() => ensureMailCollectorPassword(path, COLLECTOR, false)).toThrow(
      'not a generated collector password'
    );
  });
});

describe('renderMailCollectorEnv', () => {
  const password = 'a'.repeat(64);

  it('turns the Caddy route off when the profile is off', () => {
    expect(renderMailCollectorEnv({}, null)).toBe('SAM_MAIL_COLLECTOR=off\n');
  });

  it('turns it on with the generated password, host label and UI port', () => {
    expect(renderMailCollectorEnv(COLLECTOR, password)).toBe(
      [
        'SAM_MAIL_COLLECTOR=on',
        'MAIL_COLLECTOR_HOST_LABEL=mail',
        'MAIL_COLLECTOR_UI_PORT=8025',
        'MAIL_COLLECTOR_UI_USER=collector',
        `MAIL_COLLECTOR_UI_PASSWORD=${password}`,
        '',
      ].join('\n')
    );
  });

  it('refuses to turn it on without the password, or on a host SAM serves', () => {
    expect(() => renderMailCollectorEnv(COLLECTOR, null)).toThrow(
      'needs its generated UI password'
    );
    for (const label of ['api', 'app', 'ws-abc', 'Mail', 'a.b']) {
      expect(() =>
        renderMailCollectorEnv({ ...COLLECTOR, MAIL_COLLECTOR_HOST_LABEL: label }, password)
      ).toThrow('MAIL_COLLECTOR_HOST_LABEL');
    }
  });
});

describe('writeMailCollectorFiles', () => {
  const password = 'b'.repeat(64);
  let dir: string;
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'sam-mail-files-'));
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  it('gives Mailpit its own copy of the credentials, privately, while the profile is on', () => {
    const changed = writeMailCollectorFiles(dir, COLLECTOR, password);
    expect(changed.map((path) => path.slice(dir.length + 1)).sort()).toEqual([
      'mail-collector-ui.env',
      'mail-collector.env',
    ]);
    expect(readFileSync(join(dir, 'mail-collector-ui.env'), 'utf8')).toBe(
      `MP_UI_AUTH=collector:${password}\n`
    );
    for (const name of ['mail-collector.env', 'mail-collector-ui.env']) {
      expect(statSync(join(dir, name)).mode & 0o777).toBe(0o600);
    }
    expect(writeMailCollectorFiles(dir, COLLECTOR, password)).toEqual([]);
  });

  it('turning the profile off turns the Caddy route off and removes the password copy', () => {
    writeMailCollectorFiles(dir, COLLECTOR, password);
    writeMailCollectorFiles(dir, { COMPOSE_PROFILES: 'tunnel' }, null);
    expect(readFileSync(join(dir, 'mail-collector.env'), 'utf8')).toBe('SAM_MAIL_COLLECTOR=off\n');
    expect(existsSync(join(dir, 'mail-collector-ui.env'))).toBe(false);
  });

  it('refuses to turn the collector on without the generated password', () => {
    expect(() => writeMailCollectorFiles(dir, COLLECTOR, null)).toThrow(
      'needs its generated UI password'
    );
    expect(existsSync(join(dir, 'mail-collector-ui.env'))).toBe(false);
  });
});

describe('half-applied SMTP settings', () => {
  it.each([
    [{ SMTP_FROM: 'a@b.example' }, {}, 'SMTP_FROM'],
    [{ SMTP_USERNAME: 'u' }, {}, 'SMTP_USERNAME'],
    [{}, { SMTP_PASSWORD: 'p' }, 'SMTP_PASSWORD'],
    [{ ...COLLECTOR, SMTP_USERNAME: 'u' }, {}, 'SMTP_USERNAME'],
    [{ ...COLLECTOR, SMTP_TLS: 'tls' }, {}, 'SMTP_TLS'],
    [COLLECTOR, { SMTP_PASSWORD: 'p' }, 'SMTP_PASSWORD'],
  ] as Array<[Record<string, string>, Record<string, string>, string]>)(
    'refuses %o / secrets %o',
    (box, secrets, name) => {
      expect(() => smtpWorkerVars(box, secrets, DOMAIN)).toThrow(
        `${name} set without an SMTP relay`
      );
    }
  );

  it('control: SMTP_FROM may accompany the collector', () => {
    expect(smtpWorkerVars({ ...COLLECTOR, SMTP_FROM: 'a@b.example' }, {}, DOMAIN).SMTP_FROM).toBe(
      'a@b.example'
    );
  });
});

describe('collector ports', () => {
  it.each([
    [{ MAIL_COLLECTOR_SMTP_PORT: '25' }, 'MAIL_COLLECTOR_SMTP_PORT must be'],
    [{ MAIL_COLLECTOR_UI_PORT: '70000' }, 'MAIL_COLLECTOR_UI_PORT must be'],
    [{ MAIL_COLLECTOR_UI_PORT: '80x' }, 'MAIL_COLLECTOR_UI_PORT must be'],
    [{ MAIL_COLLECTOR_SMTP_PORT: '2525', MAIL_COLLECTOR_UI_PORT: '2525' }, 'must differ'],
  ])('refuses %o', (ports, message) => {
    expect(() => mailEgressEndpoints({ ...COLLECTOR, ...ports })).toThrow(message);
  });
});
