// Literal Node bootstrap source: never serialize bundler-transformed functions.
export const canonicalSourceBootstrap = [
  '// This self-contained function is embedded in the trusted maintenance supervisor.',
  '// Test injection is local-only; production invokes it without options.',
  'async function restoreCanonicalSource(options = {}) {',
  "  const fs = await import('node:fs');",
  "  const path = await import('node:path');",
  "  const crypto = await import('node:crypto');",
  "  const { execFileSync } = await import('node:child_process');",
  '  const env = options.environment || process.env;',
  '  const commit = env.SAM_SOURCE_COMMIT;',
  "  if (!/^[a-f0-9]{40}$/.test(commit)) throw new Error('Invalid source identity');",
  "  const directory = options.directory || '/sam/source';",
  "  const work = options.work || '/sam/private/source-cache';",
  '  fs.mkdirSync(work, { recursive: true, mode: 0o700 });',
  '  const git = (...args) =>',
  "    execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();",
  "  const sha = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');",
  '  const bucketName = /^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/;',
  '  const remoteStore = (bucket, prefix) => {',
  '    if (',
  '      !/^[a-f0-9]{32}$/.test(env.CF_ACCOUNT_ID) ||',
  '      !bucketName.test(bucket) ||',
  '      !/^[a-f0-9]{32}$/.test(env.R2_ACCESS_KEY_ID) ||',
  '      !/^[a-f0-9]{64}$/.test(env.R2_SECRET_ACCESS_KEY)',
  '    )',
  "      throw new Error('Invalid source storage authority');",
  '    const root = `https://${env.CF_ACCOUNT_ID}.r2.cloudflarestorage.com/${bucket}/${prefix}`;',
  '    // Credentials exist on disk only for one request, in a private directory.',
  '    const request = (key, file, put) => {',
  "      const scratch = fs.mkdtempSync(path.join(work, 'r2-'));",
  "      const config = path.join(scratch, 'curl.conf');",
  '      let status;',
  '      try {',
  '        fs.writeFileSync(config, `user = "${env.R2_ACCESS_KEY_ID}:${env.R2_SECRET_ACCESS_KEY}"\\n`, {',
  '          mode: 0o600,',
  '        });',
  '        status = execFileSync(',
  "        'curl',",
  '        [',
  "          '--config',",
  '          config,',
  "          '--silent',",
  "          '--proto',",
  "          '=https',",
  "          '--max-time',",
  "          '600',",
  "          '--max-filesize',",
  "          key.endsWith('.json') ? '16384' : '1073741824',",
  "          '--aws-sigv4',",
  "          'aws:amz:auto:s3',",
  '          ...(put',
  "            ? ['--request', 'PUT', '--header', 'If-None-Match: *', '--upload-file', file]",
  '            : []),',
  "          '--output',",
  "          put ? path.join(scratch, 'response') : file,",
  "          '--write-out',",
  "          '%{http_code}',",
  '          `${root}/${key}`,',
  '        ],',
  "        { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }",
  '        );',
  '      } finally {',
  '        fs.rmSync(scratch, { recursive: true, force: true });',
  '      }',
  "      if (put ? !['200', '201', '204', '412'].includes(status) : !['200', '404'].includes(status))",
  '        throw new Error(`Source storage request failed (HTTP ${status})`);',
  "      return status !== '404';",
  '    };',
  '    return {',
  '      get: (key, file) => request(key, file, false),',
  '      put: (key, file) => request(key, file, true),',
  '    };',
  '  };',
  "  const store = options.store || remoteStore(env.SAM_ARTIFACTS_BUCKET, 'installer/source');",
  '  // Read-only shared cache in the deterministic per-account state bucket. The',
  '  // deployment engine publishes to it; any fault here only means a GitHub clone.',
  '  let shared = options.shared;',
  '  if (!shared && env.SAM_BUILD_CACHE_BUCKET) {',
  '    try {',
  "      shared = remoteStore(env.SAM_BUILD_CACHE_BUCKET, 'installer-cache/source');",
  '    } catch {',
  '      shared = undefined;',
  '    }',
  '  }',
  "  const manifestFile = path.join(work, 'manifest.json');",
  "  const bundle = path.join(work, 'source.bundle');",
  '  const manifestKey = `${commit}.json`;',
  '  const expected = env.SAM_SOURCE_IDENTITY ? JSON.parse(env.SAM_SOURCE_IDENTITY) : undefined;',
  '  const valid = value => value && value.version === 1 && value.commit === commit && /^[a-f0-9]{40}$/.test(value.tree) && /^[a-f0-9]{64}$/.test(value.bundleSHA256) && Number.isSafeInteger(value.bundleBytes) && value.bundleBytes > 0 && value.bundleBytes <= 1073741824;',
  "  if (expected && !valid(expected)) throw new Error('Invalid accepted source identity');",
  "  const identical = (left,right) => ['version','commit','tree','bundleSHA256','bundleBytes'].every(key => left[key] === right[key]);",
  '  let manifest;',
  "  let origin = 'installation';",
  '  if (await store.get(manifestKey, manifestFile)) {',
  "    manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));",
  "    if (expected && !identical(expected, manifest)) throw new Error('Accepted source identity changed');",
  "    if (!valid(manifest)) throw new Error('Invalid canonical source manifest');",
  '    if (',
  '      !(await store.get(`objects/${manifest.bundleSHA256}.bundle`, bundle)) ||',
  '      fs.statSync(bundle).size !== manifest.bundleBytes ||',
  '      sha(bundle) !== manifest.bundleSHA256',
  '    )',
  "      throw new Error('Canonical source bundle integrity failure');",
  "    git('clone', bundle, directory);",
  '  } else {',
  "    if (expected) throw new Error('Accepted canonical source manifest missing');",
  '    if (shared) {',
  '      try {',
  '        const candidate = (await shared.get(manifestKey, manifestFile))',
  "          ? JSON.parse(fs.readFileSync(manifestFile, 'utf8'))",
  '          : undefined;',
  '        if (',
  '          valid(candidate) &&',
  '          (await shared.get(`objects/${candidate.bundleSHA256}.bundle`, bundle)) &&',
  '          fs.statSync(bundle).size === candidate.bundleBytes &&',
  '          sha(bundle) === candidate.bundleSHA256',
  '        ) {',
  "          git('clone', bundle, directory);",
  '          // The shared manifest only locates bytes. Authority is the approved commit',
  '          // hash: its tree must be the one the manifest claims, and the bundle may',
  '          // carry no refs (tags or branches) beyond the HEAD-only bundle we publish.',
  '          if (',
  "            git('-C', directory, 'rev-parse', `${commit}^{tree}`) !== candidate.tree ||",
  "            git('-C', directory, 'for-each-ref')",
  '          )',
  "            throw new Error('Shared source identity mismatch');",
  '          manifest = {',
  '            version: 1,',
  '            commit,',
  '            tree: candidate.tree,',
  '            bundleSHA256: candidate.bundleSHA256,',
  '            bundleBytes: candidate.bundleBytes,',
  '          };',
  "          origin = 'shared';",
  '        }',
  '      } catch {',
  '        manifest = undefined;',
  '      }',
  '      if (!manifest) {',
  '        fs.rmSync(directory, { recursive: true, force: true });',
  '        fs.rmSync(bundle, { force: true });',
  '      }',
  '    }',
  '    if (!manifest) {',
  "      origin = 'upstream';",
  '      git(',
  "        'clone',",
  "        options.remote || 'https://github.com/raphaeltm/simple-agent-manager.git',",
  '        directory',
  '      );',
  "      git('-C', directory, 'checkout', '--detach', commit);",
  "      git('-C', directory, 'bundle', 'create', bundle, 'HEAD');",
  '      manifest = {',
  '        version: 1,',
  '        commit,',
  "        tree: git('-C', directory, 'rev-parse', `${commit}^{tree}`),",
  '        bundleSHA256: sha(bundle),',
  '        bundleBytes: fs.statSync(bundle).size,',
  '      };',
  '    }',
  '    const key = `objects/${manifest.bundleSHA256}.bundle`;',
  '    await store.put(key, bundle);',
  "    const check = path.join(work, 'readback.bundle');",
  '    if (!(await store.get(key, check)) || sha(check) !== manifest.bundleSHA256)',
  "      throw new Error('Canonical source publication failed');",
  '    fs.writeFileSync(manifestFile, JSON.stringify(manifest), { mode: 0o600 });',
  '    await store.put(manifestKey, manifestFile);',
  "    const observed = path.join(work, 'readback.json');",
  '    if (',
  '      !(await store.get(manifestKey, observed)) ||',
  "      fs.readFileSync(observed, 'utf8') !== fs.readFileSync(manifestFile, 'utf8')",
  '    )',
  "      throw new Error('Canonical source association conflict');",
  '  }',
  "  git('-C', directory, 'checkout', '--detach', commit);",
  '  if (',
  "    git('-C', directory, 'rev-parse', 'HEAD') !== commit ||",
  "    git('-C', directory, 'rev-parse', `${commit}^{tree}`) !== manifest.tree ||",
  "    git('-C', directory, 'rev-parse', '--is-shallow-repository') !== 'false' ||",
  "    git('-C', directory, 'status', '--porcelain')",
  '  )',
  "    throw new Error('Canonical source identity mismatch');",
  "  fs.mkdirSync(path.join(directory, '.wrangler'), { recursive: true, mode: 0o700 });",
  '  fs.writeFileSync(',
  "    path.join(directory, '.wrangler', 'installer-source-identity.json'),",
  '    JSON.stringify(manifest),',
  '    { mode: 0o600 }',
  '  );',
  '  // Keep a bundle the shared cache did not supply, for the engine to offer to later',
  '  // installations once the state bucket exists (installer-build-cache.mjs).',
  "  if (origin !== 'shared') {",
  '    try {',
  "      fs.renameSync(bundle, path.join(directory, '.wrangler', `installer-source-${origin}.bundle`));",
  '    } catch {',
  '      /* Publication is an optimization; the restored source is already verified. */',
  '    }',
  '  }',
  '  fs.rmSync(work, { recursive: true, force: true });',
  '  return manifest;',
  '}',
].join('\n');
