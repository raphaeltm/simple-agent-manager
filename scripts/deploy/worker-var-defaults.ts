/**
 * API Worker variables that `apps/api/wrangler.toml` deliberately does NOT ship.
 *
 * Cloudflare caps the text bindings (plain-text vars plus secrets) one Worker may carry, and every
 * top-level `[vars]` entry becomes a binding on every deployed API Worker. An entry whose value is
 * exactly what the code already does when the var is absent costs a binding and buys nothing, so it
 * is omitted from `[vars]` and its value is recorded here instead.
 *
 * Consumers:
 * - `sync-wrangler-config.ts` compares GitHub Environment overrides against these values, so an
 *   override of an omitted var is still reported in the deploy log and job summary when it differs
 *   from the code default (`.claude/rules/70`). The values are never emitted as bindings.
 * - `apps/api/tests/unit/config/omitted-worker-var-defaults.test.ts` proves each value is what
 *   production code resolves when the var is absent, by running the real read path both ways.
 *   Changing one of these code defaults therefore fails that test until the change is made here
 *   too, deliberately, because it changes what every deployment runs with.
 * - `scripts/quality/sync-wrangler-config.test.ts` proves the staging and production generated
 *   configs resolve every var to the same value as shipping these defaults would, and that
 *   `[vars]` does not re-add a name recorded here.
 *
 * To run a deployment with a different value, add the var to `[vars]` with that value and delete it
 * here (it then ships as a binding), or set a GitHub Environment variable when the name is in the
 * `getOptionalProcessEnvVars` list. Never add a var to `[vars]` with the value its code already
 * defaults to.
 *
 * Two kinds of omitted var are deliberately NOT recorded, so an override of them is forwarded but not
 * reported: growing allowlists whose code default changes whenever a provider is added
 * (`CREDENTIAL_LIMIT_SUPPORTED_PROVIDERS`, `_SOURCES`, `_WINDOW_TYPES`), and vars read only inline in
 * a request handler (`CREDENTIAL_LIMIT_USAGE_CALLBACK_MAX_BODY_BYTES`, `_RATE_LIMIT_RPM`,
 * `_RATE_LIMIT_WINDOW_SECONDS`), which the proof test cannot call.
 */
